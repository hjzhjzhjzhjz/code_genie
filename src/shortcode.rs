// =========================================================================
// ⚡ 三级前缀简码：全码算完后自动生成，以「简码效率」为唯一目标
// =========================================================================
//
// 与已移除的旧简码功能（checkpoint v2 之前）不同，这里**不参与退火**：
// 全码一旦定稿，每个字的编码就固定了，简码只能是全码的前缀。此时「怎么把有限的
// 简码位分给哪些字」是一个纯分配问题，最优解可以一次性算出来，不需要再迭代搜索，
// 也不会反过来扰动全码质量。
//
// ## 效率的定义与两种口径
//
// 目标只有一个：最小化**字频加权平均上屏码长**
//     Σ(字频 × 上屏码长) / Σ字频
// 没有简码的字用全码上屏；有简码的字用简码上屏。
//
// 「上屏码长」怎么数，有两套口径，可用 `[shortcode] padding_space` 或
// CLI `--padding-space` 切换（**本项目缺省为补空格档**）：
//
//   · 码串长度（旧档，`padding_space = false`）：码表里写几个字符就算几键。
//     一级 `a_` 2 键、二级 `ab` 2 键、三级 `abc` 3 键、全码 4 键（个别 3 键）。
//   · 补空格（缺省，测评用码表）：测评对「首选且未满 4 码」的编码补一个 `_` 后再计数。
//     为了让空格只补一次，这一档的一级简码直接写成单字母 `a`（测评补成 `a_`，2 键），
//     二级 `ab` → `ab_`（3 键），三级 `abc` → `abc_`（4 键），3 键全码 `abc` → `abc_`。
//     因此三级简码在测评口径下**不省键**，算法不会分配它；一级省 2 键、二级省 1 键。
//
// 两档的加权码长数值不可直接比较，只有同档内比较才有意义。补空格档只模拟
// 「短码补空格」，不计入全码重码的选重键（测评里那部分会再 +1 键）。
//
// ## 与宇浩测评两个指标的关系（容易混淆，务必看清）
//
//   · 测评「速度当量 / 按键数」用 `全碼加選重鍵表`：短码补 `_`、非首选加选重键。
//     本档的补空格规则与它同源（少了全码重码的选重键）。
//   · 测评「簡碼效率加權碼長」(`shortCodeEfficiencyService.ts`) 反而用**不含**下划线
//     与选重键的纯编码长度——源码注释写明是为了避免「3 碼簡碼補下劃線後誤判為無效
//     簡碼」。它更接近默认的「码串长度」档；差别是测评码表的一级简码通常写单字母
//     `a`（1 键），而本项目历史格式写 `a_`（2 键）。
//
// 因此 `padding_space` 优化的是「实际按键数」口径；测评源码的「簡碼效率加權碼長」
// 用纯编码长度，两者不是同一口径，数值不能直接比大小。
//
// ## 本项目采用的口径（用户 2026-11-08 明确）
//
// 一/二/三级简码上屏**都要按一次空格**：三级简码 `abc` + 空格 = 4 键，与全码持平，
// 本来就不省键。因此一/二级只分配 1/2 级（25 + 625 = 650 字）；三级简码**专职消解
// 动态重码**（2026-11-10 起）：不省键但让字退出全码重码组，测评「簡碼效率」的
// 纯码长口径（3 键 < 4 键）同样受益。配置缺省已改为 `padding_space = true`；
// 要回到旧档显式写 `false`，或给独立命令传 `--padding-space=false`。
// `output-v8-enc210-40m/` 的测评码表已切成补空格档。
//
// 实测提示（V8 全量字频）：两档按键数差异几乎全部来自**一级简码的写法**——
// 默认档的 `a_` 在测评按键表里会被再补一个 `_`（记 3 键），单字母 `a` 只补成
// `a_`（2 键）。三级简码按按键数口径零收益，但按测评纯码长口径记 3 键（省 1），
// 且专职消解动态重码——现在只分配给「一二级轮之后仍消解不掉」的全码重码组成员。
//
// ## 约束
//
// 1. 简码必须是该字全码的前缀（前 1/2/3 键）。
// 2. 同一个简码串最多分配给一个字，否则简码自身重码、要选重。
// 3. 简码的**上屏串**不能与别人的全码上屏串相同（例如 3 键全码 `abc` 与三级简码
//    `abc` 会撞码；补空格口径下两者都是 `abc_`）。全码比简码长时是正常的前缀码。
// 4. 某级简码的上屏码长不小于全码上屏码长时，该级无收益，直接跳过。
//
// ## 动态重码（宇浩测评「動態選重率」口径，2026-11-10 加入）
//
// 测评对「每字最短码」按码串分组：同组 ≥2 字时，组内除最高频字外的字频全部计入
// 动态选重损失。本方案的简码唯一且不撞全码，所以简码本身不产生新组；损失的唯一
// 来源是**全码重码组**（同全码 ≥2 字）——只要组内**任意一个**成员拿到简码，它的
// 最短码就变成简码、退出该组，剩余成员成单字组，损失清零。
//
// 用户口径（2026-11-10 明确）：**一级和二级简码专职降低码长，三级简码专职消解
// 动态重码**。因此分配分两轮：
//   第一轮（一二级降码长）：按字频降序省键贪心，只试 1→2 级，与旧逻辑一致。
//   第二轮（三级消重码）：第一轮后仍无成员拿到简码的重码组，按组损失降序，
//     派组内最高频成员抢三级前缀位；补空格档下三级 + 空格 = 4 键与全码持平，
//     **允许等键分配**——收益不是省键，而是该字退出重码组、动态选重清零，
//     同时测评「簡碼效率」（纯码长口径）里 3 键 < 4 键仍然受益。
//     3 码全码与三级等长等上屏串（都会补成 `abc_`），不能拿三级，照旧跳过。
//
// 这不再是纯省键意义下的最优（三级位会让给重码组），但用户口径明确：
// 动态重码率最低优先。动态重码率按**传入的字频表**计算——想要对齐测评的北語簡體
// 字频，用 `shortcode --freq <北语字频表>` 传入即可；缺省用拆分表自带字频近似。
//
// ## 为什么第一轮按字频降序贪心就是最优
//
// 每个简码位（按码串区分）是一个独立资源；一个字最多占一个位，占的位越短收益
// `字频 × (全码长 − 上屏码长)` 越大。按字频降序处理、每个字取「最短且尚未被占用」
// 的前缀，等价于把每个位分给能使用它且字频最高的字：若某个位被更低频的字占了，
// 把位换给更高频的字不会让任何其他人变差，收益只会增加。因此不需要退火或搜索。
//
// 一级位只有 26 个、二级 676 个，先试一级再二级，天然保证高频字优先吃满稀缺的短码位。
// =========================================================================

use std::collections::{HashMap, HashSet};

/// 一条全码记录：`(字, 全码, 字频)`。字频与退火评分同源（`files.splits` 第三列）。
pub type 全码条目 = (char, String, u64);

/// 宇浩测评的默认最大码长：短于它的首选编码补一个 `_`。
pub const 测评最大码长: usize = 4;

/// 「上屏码长」的计算口径。两档的统计数值不可直接比较。
/// 注意：这里的 `Default` 只供 `简码统计` 派生使用；业务缺省口径由
/// `Config.shortcode.padding_space`（默认 `true` → 补空格档）决定。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum 码长口径 {
    /// 项目默认：码表字符串长度（一级 `a_` 记 2 键）
    #[default]
    码串长度,
    /// 宇浩测评：首选且未满 4 码的编码补一个 `_` 后计数
    补空格,
}

impl 码长口径 {
    pub fn 名称(self) -> &'static str {
        match self {
            码长口径::码串长度 => "码串长度",
            码长口径::补空格 => "补空格（按键数口径）",
        }
    }

    /// 配置 / CLI 的布尔开关 → 口径
    pub fn 由开关(补空格: bool) -> Self {
        if 补空格 {
            码长口径::补空格
        } else {
            码长口径::码串长度
        }
    }

    /// 该口径下实际用于「上屏」和「撞码判定」的码串。
    /// 补空格档严格对齐测评 CLI：没有编码终止指示符时，只要 `长度 < 最大码长`
    /// 就无条件追加一个 `_`（包括已带 `_` 的串，所以这一档的一级简码必须写成单字母）。
    pub fn 上屏串(self, 码串: &str) -> String {
        let 长 = 码串.chars().count();
        match self {
            码长口径::码串长度 => 码串.to_string(),
            码长口径::补空格 if 长 < 测评最大码长 => format!("{码串}_"),
            码长口径::补空格 => 码串.to_string(),
        }
    }

    pub fn 上屏码长(self, 码串: &str) -> usize {
        let 长 = 码串.chars().count();
        match self {
            码长口径::码串长度 => 长,
            码长口径::补空格 if 长 < 测评最大码长 => 长 + 1,
            码长口径::补空格 => 长,
        }
    }
}

/// 一条已分配的简码
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 简码条目 {
    pub 字: char,
    /// 一级带 `_`（空格上屏），二/三级为纯字母前缀
    pub 码: String,
    pub 字频: u64,
    /// 1 / 2 / 3
    pub 级别: usize,
}

/// 汇总统计（用于日志与 `简码表.txt` 头部）
#[derive(Debug, Clone, Default, PartialEq)]
pub struct 简码统计 {
    /// 本次分配所用的口径（统计数值只在同一口径内可比）
    pub 口径: 码长口径,
    pub 全码字数: usize,
    pub 简码字数: usize,
    /// 下标 0/1/2 对应 1/2/3 级
    pub 各级条数: [usize; 3],
    pub 总字频: u128,
    pub 覆盖字频: u128,
    /// 全部用全码时的字频加权码长
    pub 基线码长: f64,
    /// 启用简码后的字频加权码长
    pub 简码后码长: f64,
    /// 不分配任何简码时的动态选重率（全部全码重码组都计损失，宇浩测评口径）
    pub 动态重码基线: f64,
    /// 分配简码后的剩余动态选重率（仅「无任何成员拿到简码」的全码重码组计损失）
    pub 动态重码率: f64,
}

impl 简码统计 {
    /// 简码命中的字频占总字频的比例（0~1）
    pub fn 覆盖频率(&self) -> f64 {
        if self.总字频 == 0 {
            0.0
        } else {
            self.覆盖字频 as f64 / self.总字频 as f64
        }
    }

    /// 平均每字省下多少键
    pub fn 省键(&self) -> f64 {
        self.基线码长 - self.简码后码长
    }
}

#[derive(Debug, Clone)]
pub struct 简码结果 {
    pub 条目: Vec<简码条目>,
    pub 统计: 简码统计,
}

/// 按指定口径生成三级前缀简码。口径既决定「省不省键」的分配决策，也决定统计数值。
///
/// 两轮分配：一/二级按字频降序省键贪心（专职降码长）；之后仍消解不掉的全码
/// 重码组按组损失降序派代表抢三级前缀位（专职消动态重码，允许等键）。
/// 动态重码率按传入字频计算，见模块头注释。
///
/// 同一字若在全码表里出现多行，只保留字频最大的那行；相同字频按字符码点排序，
/// 保证输出确定、可复现。
pub fn 生成_按口径(全码表: &[全码条目], 口径: 码长口径) -> 简码结果 {
    // 1. 去重：字 → (全码, 字频)，重复时取字频最大者
    let mut 去重: HashMap<char, (String, u64)> = HashMap::with_capacity(全码表.len());
    for (字, 码, 频) in 全码表 {
        if 码.is_empty() {
            continue;
        }
        去重
            .entry(*字)
            .and_modify(|(旧码, 旧频)| {
                if *频 > *旧频 {
                    *旧码 = 码.clone();
                    *旧频 = *频;
                }
            })
            .or_insert_with(|| (码.clone(), *频));
    }

    // 2. 全码的**上屏串**集合：简码不得与之撞码。补空格档下 3 键全码 `abc` 和
    //    三级简码 `abc` 都会变成 `abc_`，所以用上屏串比对才拦得住。
    let 全码字数 = 去重.len();
    // 拥有 String 而不是借用：下面 `去重.into_iter()` 会消耗整张表。
    let 全码集合: HashSet<String> = 去重.values().map(|(码, _)| 口径.上屏串(码)).collect();
    let 总字频: u128 = 去重.values().map(|(_, 频)| *频 as u128).sum();
    let 基线加权: u128 = 去重
        .values()
        .map(|(码, 频)| 口径.上屏码长(码) as u128 * *频 as u128)
        .sum();

    // 3. 按字频降序处理（同频按字码点，保证确定性）。
    //    零频字不参与分配：它们对加权码长没有贡献，不该占掉前缀位、也不该刷出
    //    几万条无意义的简码（CLI 对全量码表补简码时会遇到大量零频冷僻字）。
    let mut 候选: Vec<(char, String, u64)> = 去重
        .into_iter()
        .filter(|(_, (_, 频))| *频 > 0)
        .map(|(字, (码, 频))| (字, 码, 频))
        .collect();
    候选.sort_by(|a, b| b.2.cmp(&a.2).then_with(|| a.0.cmp(&b.0)));

    // 4. 动态重码组：按全码上屏串分组，组内 ≥2 字即为测评口径下的动态选重损失源。
    //    组损失 = Σ组频 − 组内最大频（组内最高频字作首选，其余都要选重）。
    let mut 组表: HashMap<String, Vec<usize>> = HashMap::new();
    for (i, (_, 码, _)) in 候选.iter().enumerate() {
        组表.entry(口径.上屏串(码)).or_default().push(i);
    }
    let mut 重码组: Vec<(String, Vec<usize>)> = 组表
        .into_iter()
        .filter(|(_, 成员)| 成员.len() >= 2)
        .collect();
    重码组.sort_by(|a, b| {
        let 损失 = |组: &(String, Vec<usize>)| -> u128 {
            let 频们: Vec<u64> = 组.1.iter().map(|&i| 候选[i].2).collect();
            let 最大 = 频们.iter().max().copied().unwrap_or(0);
            频们.iter().map(|&f| f as u128).sum::<u128>() - 最大 as u128
        };
        损失(b).cmp(&损失(a)).then_with(|| a.0.cmp(&b.0))
    });

    // 5. 两轮分配。`抢位` 给定一个字的全码与候选级别列表，按序找可用前缀位；
    //    撞码/占用判定与旧逻辑一致；`允许等键` 供三级消重码轮使用（补空格档下
    //    三级 + 空格与全码同为 4 键，收益是退出重码组而非省键）。
    fn 抢位(
        全码: &str,
        口径: 码长口径,
        全码集合: &HashSet<String>,
        已占用: &mut HashSet<String>,
        级别们: &[usize],
        允许等键: bool,
    ) -> Option<(String, usize, usize)> {
        let 全码长 = 全码.chars().count();
        let 全码上屏长 = 口径.上屏码长(全码);
        for &级别 in 级别们 {
            if 全码长 <= 级别 {
                continue; // 前缀不比全码短（3 码全码与三级等长等上屏串，不能拿三级）
            }
            let 前缀: String = 全码.chars().take(级别).collect();
            let 码 = if 级别 == 1 {
                match 口径 {
                    // 默认档：一级简码显式带空格，与历史 `简码表.txt` 格式一致（2 键）
                    码长口径::码串长度 => format!("{前缀}_"),
                    // 补空格档：写成单字母，空格交给测评补；写成 `a_` 会被补成 `a__`
                    码长口径::补空格 => 前缀,
                }
            } else {
                前缀
            };
            let 上屏串 = 口径.上屏串(&码);
            let 上屏长 = 口径.上屏码长(&码);
            if !允许等键 && 上屏长 >= 全码上屏长 {
                continue; // 该级在该口径下不省键（补空格档的三级正是如此）
            }
            if 全码集合.contains(&上屏串) || 已占用.contains(&上屏串) {
                continue;
            }
            已占用.insert(上屏串);
            return Some((码, 级别, 上屏长));
        }
        None
    }

    let mut 已占用: HashSet<String> = HashSet::new();
    let mut 预分配: HashMap<char, (String, usize, usize)> = HashMap::new();

    // 第一轮：一二级降码长——按字频降序省键贪心（只试 1→2 级）。
    for (字, 全码, _) in &候选 {
        if let Some(分配) = 抢位(全码, 口径, &全码集合, &mut 已占用, &[1, 2], false)
        {
            预分配.insert(*字, 分配);
        }
    }

    // 第二轮：三级消重码——第一轮后仍无成员拿到简码的重码组，按组损失降序
    // （重码组构建时已排好）派组内最高频成员抢三级位；等键也分配。
    // 组内成员全码相同 → 三级前缀完全相同，派谁都一样；选最高频者与「首选字拿简码」
    // 直觉一致。
    for (_, 成员) in &重码组 {
        if 成员.iter().any(|&i| 预分配.contains_key(&候选[i].0)) {
            continue; // 该组已在第一轮消解
        }
        let Some(&代表) = 成员
            .iter()
            .max_by_key(|&&i| (候选[i].2, std::cmp::Reverse(候选[i].0)))
        else {
            continue;
        };
        let (字, 全码, _) = &候选[代表];
        if let Some(分配) = 抢位(全码, 口径, &全码集合, &mut 已占用, &[3], true) {
            预分配.insert(*字, 分配);
        }
    }

    // 6. 产出条目与统计（按候选顺序，确定可复现）。
    let mut 条目: Vec<简码条目> = Vec::new();
    let mut 各级条数 = [0usize; 3];
    let mut 覆盖字频 = 0u128;
    let mut 简码后加权: u128 = 0;
    for (字, 全码, 字频) in &候选 {
        let 全码上屏长 = 口径.上屏码长(全码);
        let 上屏码长 = match 预分配.get(字) {
            Some((码, 级别, 上屏长)) => {
                各级条数[级别 - 1] += 1;
                覆盖字频 += *字频 as u128;
                条目.push(简码条目 {
                    字: *字,
                    码: 码.clone(),
                    字频: *字频,
                    级别: *级别,
                });
                *上屏长
            }
            None => 全码上屏长,
        };
        简码后加权 += 上屏码长 as u128 * *字频 as u128;
    }

    // 7. 动态重码统计（宇浩测评口径：每字最短码分组，组内除最高频外全计损失）。
    //    组内任一成员拿到简码即消解；零频字不进候选、不计损失（想按北语频精确
    //    计算，用 `shortcode --freq <北语字频表>` 传入字频再跑）。
    let mut 动态基线损失 = 0u128;
    let mut 动态剩余损失 = 0u128;
    for (_, 成员) in &重码组 {
        let 频们: Vec<u64> = 成员.iter().map(|&i| 候选[i].2).collect();
        let 最大 = 频们.iter().max().copied().unwrap_or(0);
        let 组损失 = 频们.iter().map(|&f| f as u128).sum::<u128>() - 最大 as u128;
        动态基线损失 += 组损失;
        if !成员.iter().any(|&i| 预分配.contains_key(&候选[i].0)) {
            动态剩余损失 += 组损失;
        }
    }

    let 分母 = 总字频 as f64;
    let 统计 = 简码统计 {
        口径,
        全码字数,
        简码字数: 条目.len(),
        各级条数,
        总字频,
        覆盖字频,
        基线码长: if 分母 > 0.0 {
            基线加权 as f64 / 分母
        } else {
            0.0
        },
        简码后码长: if 分母 > 0.0 {
            简码后加权 as f64 / 分母
        } else {
            0.0
        },
        动态重码基线: if 分母 > 0.0 {
            动态基线损失 as f64 / 分母
        } else {
            0.0
        },
        动态重码率: if 分母 > 0.0 {
            动态剩余损失 as f64 / 分母
        } else {
            0.0
        },
    };
    简码结果 { 条目, 统计 }
}

/// `简码表.txt` 全文（仿历史三级分段格式，带效率指标头部）
