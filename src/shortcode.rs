        let 目录 = std::env::temp_dir().join(format!("cg_shortcode_{}", std::process::id()));
        std::fs::create_dir_all(&目录).unwrap();
        let 完整 = 目录.join("完整码表.txt");
        let 全码段 = "甲\tabcd\n乙\tefgh\n";
        std::fs::write(&完整, 全码段).unwrap();
        let 结果 = 生成(&造(&[('甲', "abcd", 3), ('乙', "efgh", 1)]));

        let 频: HashMap<char, u64> = HashMap::from([('甲', 3), ('乙', 1)]);
        保存(目录.to_str().unwrap(), &结果, &频, "测试");
        let 一次 = std::fs::read_to_string(&完整).unwrap();
        保存(目录.to_str().unwrap(), &结果, &频, "测试");
        let 二次 = std::fs::read_to_string(&完整).unwrap();

        assert_eq!(一次, 二次, "重复运行内容应完全一致");
        assert!(!二次.contains('#'), "整份码表不应有注释行");
        assert_eq!(二次.matches(简码段标记).count(), 0, "新格式不写标记");
