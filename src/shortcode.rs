    /// 一二级省键贪心（码长目标）；重码组若代表在效率轮已拿到简码即消解，
    /// 三级轮只处理剩余组。
    #[test]
    fn 重码组优先消除动态重码() {
        let 表 = 造(&[('丙', "abxy", 50), ('甲', "abcd", 100), ('乙', "abcd", 10)]);
        let r = 生成(&表);
        let 甲 = r.条目.iter().find(|e| e.字 == '甲').unwrap();
        let 丙 = r.条目.iter().find(|e| e.字 == '丙').unwrap();
        // 效率轮：甲(100) 最高频先拿一级；丙(50) 退二级；乙(10) 无位
        assert_eq!(甲.码, "a_", "最高频字拿一级");
        assert_eq!(丙.码, "ab", "次高频字拿二级");
        assert!(
            !r.条目.iter().any(|e| e.字 == '乙'),
            "乙无可用一二级位，且组已被甲消解、无需三级兜底"
        );
        assert_eq!(r.统计.各级条数, [1, 1, 0]);
        // 组 [甲,乙] 已消解 → 剩余动态重码 0；基线为组损失 10 / 总频 160
        assert!((r.统计.动态重码率 - 0.0).abs() < 1e-12);
        assert!((r.统计.动态重码基线 - 10.0 / 160.0).abs() < 1e-12);
    }

    /// 补空格档下三级简码专职消重码：效率轮一二级分配完后，仍消解不掉的重码组
    /// 按组损失降序派代表拿三级位（等键也分配）。
    #[test]
    fn 补空格档三级兜底消重码() {
        let 表 = 造(&[
            ('甲', "abxa", 100),
            ('乙', "abxa", 10),
            ('丙', "abya", 50),
            ('丁', "abya", 5),
            ('己', "abza", 20),
            ('庚', "abza", 2),
        ]);
        let r = 生成_按口径(&表, 码长口径::补空格);
        assert_eq!(r.条目.iter().find(|e| e.字 == '甲').unwrap().码, "a");
        assert_eq!(r.条目.iter().find(|e| e.字 == '丙').unwrap().码, "ab");
        let 己 = r.条目.iter().find(|e| e.字 == '己').unwrap();
        assert_eq!(己.码, "abz", "剩余重码组的代表拿三级兜底");
        assert_eq!(己.级别, 3);
        assert!(r
            .条目
            .iter()
            .all(|e| e.字 != '乙' && e.字 != '丁' && e.字 != '庚'));
        let 总频 = 187.0;
        assert!((r.统计.动态重码基线 - (10 + 5 + 2) as f64 / 总频).abs() < 1e-12);
        assert!((r.统计.动态重码率 - 0.0).abs() < 1e-12, "三个组全部消解");
    }

