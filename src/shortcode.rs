// =========================================================================
// ⚡ 三级前缀简码：全码算完后自动生成，以「简码效率」为唯一目标
// =========================================================================
//
// 与已移除的旧简码功能（checkpoint v2 之前）不同，这里**不参与退火**：
// 全码一旦定稿，每个字的编码就固定了，简码只能是全码的前缀。此时「怎么把有限的
// 简码位分给哪些字」是一个纯分配问题，最优解可以一次性算出来，不需要再迭代搜索，
// 也不会反过来扰动全码质量。
//
// ## 效率的定义与两种口径
//
// 目标只有一个：最小化**字频加权平均上屏码长**
//     Σ(字频 × 上屏码长) / Σ字频
// 没有简码的字用全码上屏；有简码的字用简码上屏。
//
// 「上屏码长」怎么数，有两套口径，可用 `[shortcode] padding_space` 或
// CLI `--padding-space` 切换（**本项目缺省为补空格档**）：
//
//   · 码串长度（旧档，`padding_space = false`）：码表里写几个字符就算几键。
//     一级 `a_` 2 键、二级 `ab` 2 键、三级 `abc` 3 键、全码 4 键（个别 3 键）。
//   · 补空格（缺省，测评用码表）：测评对「首选且未满 4 码」的编码补一个 `_` 后再计数。
//     为了让空格只补一次，这一档的一级简码直接写成单字母 `a`（测评补成 `a_`，2 键），
//     二级 `ab` → `ab_`（3 键），三级 `abc` → `abc_`（4 键），3 键全码 `abc` → `abc_`。
//     因此三级简码在测评口径下**不省键**，算法不会分配它；一级省 2 键、二级省 1 键。
//
// 两档的加权码长数值不可直接比较，只有同档内比较才有意义。补空格档只模拟
// 「短码补空格」，不计入全码重码的选重键（测评里那部分会再 +1 键）。
//
// ## 与宇浩测评两个指标的关系（容易混淆，务必看清）
//
//   · 测评「速度当量 / 按键数」用 `全碼加選重鍵表`：短码补 `_`、非首选加选重键。
//     本档的补空格规则与它同源（少了全码重码的选重键）。
//   · 测评「簡碼效率加權碼長」(`shortCodeEfficiencyService.ts`) 反而用**不含**下划线
//     与选重键的纯编码长度——源码注释写明是为了避免「3 碼簡碼補下劃線後誤判為無效
//     簡碼」。它更接近默认的「码串长度」档；差别是测评码表的一级简码通常写单字母
//     `a`（1 键），而本项目历史格式写 `a_`（2 键）。
//
// 因此 `padding_space` 优化的是「实际按键数」口径；测评源码的「簡碼效率加權碼長」
// 用纯编码长度，两者不是同一口径，数值不能直接比大小。
//
// ## 本项目采用的口径（用户 2026-11-08 明确）
//
// 一/二/三级简码上屏**都要按一次空格**：三级简码 `abc` + 空格 = 4 键，与全码持平，
// 本来就不省键。因此「优化测评簡碼效率」统一采用**补空格档**——只分配 1/2 级
// （25 + 625 = 650 字），不产出零收益的三级简码。配置缺省已改为
// `padding_space = true`；要回到旧档显式写 `false`，或给独立命令传
// `--padding-space=false`。`output-v8-enc210-40m/` 的测评码表已切成补空格档。
//
// 实测提示（V8 全量字频）：两档按键数差异几乎全部来自**一级简码的写法**——
// 默认档的 `a_` 在测评按键表里会被再补一个 `_`（记 3 键），单字母 `a` 只补成
// `a_`（2 键）。砍掉三级简码并不改变按键数，只是不再产出「按按键数看零收益」
// 的简码条目；若按测评纯码长口径衡量，砍掉三级会让「簡碼效率加權碼長」从
// 2.4287 升到 2.5831——但按「每级简码都带空格」的口径，三级本就不该计入。
//
// ## 约束
//
// 1. 简码必须是该字全码的前缀（前 1/2/3 键）。
// 2. 同一个简码串最多分配给一个字，否则简码自身重码、要选重。
// 3. 简码的**上屏串**不能与别人的全码上屏串相同（例如 3 键全码 `abc` 与三级简码
//    `abc` 会撞码；补空格口径下两者都是 `abc_`）。全码比简码长时是正常的前缀码。
// 4. 某级简码的上屏码长不小于全码上屏码长时，该级无收益，直接跳过。
//
// ## 为什么按字频降序贪心就是最优
//
// 每个简码位（按码串区分）是一个独立资源；一个字最多占一个位，占的位越短收益
// `字频 × (全码长 − 上屏码长)` 越大。按字频降序处理、每个字取「最短且尚未被占用」
// 的前缀，等价于把每个位分给能使用它且字频最高的字：若某个位被更低频的字占了，
// 把位换给更高频的字不会让任何其他人变差，收益只会增加。因此不需要退火或搜索。
//
// 一级位只有 26 个、二级 676 个、三级 17576 个，先试一级再二级/三级，
// 天然保证高频字优先吃满稀缺的短码位。
// =========================================================================

use std::collections::{HashMap, HashSet};

/// 一条全码记录：`(字, 全码, 字频)`。字频与退火评分同源（`files.splits` 第三列）。
pub type 全码条目 = (char, String, u64);

/// 宇浩测评的默认最大码长：短于它的首选编码补一个 `_`。
pub const 测评最大码长: usize = 4;

/// 「上屏码长」的计算口径。两档的统计数值不可直接比较。
/// 注意：这里的 `Default` 只供 `简码统计` 派生使用；业务缺省口径由
/// `Config.shortcode.padding_space`（默认 `true` → 补空格档）决定。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum 码长口径 {
    /// 项目默认：码表字符串长度（一级 `a_` 记 2 键）
    #[default]
    码串长度,
    /// 宇浩测评：首选且未满 4 码的编码补一个 `_` 后计数
    补空格,
}

impl 码长口径 {
    pub fn 名称(self) -> &'static str {
        match self {
            码长口径::码串长度 => "码串长度",
            码长口径::补空格 => "补空格（按键数口径）",
        }
    }

    /// 配置 / CLI 的布尔开关 → 口径
    pub fn 由开关(补空格: bool) -> Self {
        if 补空格 {
            码长口径::补空格
        } else {
            码长口径::码串长度
        }
    }

    /// 该口径下实际用于「上屏」和「撞码判定」的码串。
    /// 补空格档严格对齐测评 CLI：没有编码终止指示符时，只要 `长度 < 最大码长`
    /// 就无条件追加一个 `_`（包括已带 `_` 的串，所以这一档的一级简码必须写成单字母）。
    pub fn 上屏串(self, 码串: &str) -> String {
        let 长 = 码串.chars().count();
        match self {
            码长口径::码串长度 => 码串.to_string(),
            码长口径::补空格 if 长 < 测评最大码长 => format!("{码串}_"),
            码长口径::补空格 => 码串.to_string(),
        }
    }

    pub fn 上屏码长(self, 码串: &str) -> usize {
        let 长 = 码串.chars().count();
        match self {
            码长口径::码串长度 => 长,
            码长口径::补空格 if 长 < 测评最大码长 => 长 + 1,
            码长口径::补空格 => 长,
        }
    }
}

/// 一条已分配的简码
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 简码条目 {
    pub 字: char,
    /// 一级带 `_`（空格上屏），二/三级为纯字母前缀
    pub 码: String,
    pub 字频: u64,
    /// 1 / 2 / 3
    pub 级别: usize,
}

/// 汇总统计（用于日志与 `简码表.txt` 头部）
#[derive(Debug, Clone, Default, PartialEq)]
pub struct 简码统计 {
    /// 本次分配所用的口径（统计数值只在同一口径内可比）
    pub 口径: 码长口径,
    pub 全码字数: usize,
    pub 简码字数: usize,
    /// 下标 0/1/2 对应 1/2/3 级
    pub 各级条数: [usize; 3],
    pub 总字频: u128,
    pub 覆盖字频: u128,
    /// 全部用全码时的字频加权码长
    pub 基线码长: f64,
    /// 启用简码后的字频加权码长
    pub 简码后码长: f64,
}

impl 简码统计 {
    /// 简码命中的字频占总字频的比例（0~1）
    pub fn 覆盖频率(&self) -> f64 {
        if self.总字频 == 0 {
            0.0
        } else {
            self.覆盖字频 as f64 / self.总字频 as f64
        }
    }

    /// 平均每字省下多少键
    pub fn 省键(&self) -> f64 {
        self.基线码长 - self.简码后码长
    }
}

#[derive(Debug, Clone)]
pub struct 简码结果 {
    pub 条目: Vec<简码条目>,
    pub 统计: 简码统计,
}

/// 按指定口径生成三级前缀简码。口径既决定「省不省键」的分配决策，也决定统计数值。
///
/// 同一字若在全码表里出现多行，只保留字频最大的那行；相同字频按字符码点排序，
/// 保证输出确定、可复现。
pub fn 生成_按口径(全码表: &[全码条目], 口径: 码长口径) -> 简码结果 {
    // 1. 去重：字 → (全码, 字频)，重复时取字频最大者
    let mut 去重: HashMap<char, (String, u64)> = HashMap::with_capacity(全码表.len());
    for (字, 码, 频) in 全码表 {
        if 码.is_empty() {
            continue;
        }
        去重
            .entry(*字)
            .and_modify(|(旧码, 旧频)| {
                if *频 > *旧频 {
                    *旧码 = 码.clone();
                    *旧频 = *频;
                }
            })
            .or_insert_with(|| (码.clone(), *频));
    }

    // 2. 全码的**上屏串**集合：简码不得与之撞码。补空格档下 3 键全码 `abc` 和
    //    三级简码 `abc` 都会变成 `abc_`，所以用上屏串比对才拦得住。
    let 全码字数 = 去重.len();
    // 拥有 String 而不是借用：下面 `去重.into_iter()` 会消耗整张表。
    let 全码集合: HashSet<String> = 去重.values().map(|(码, _)| 口径.上屏串(码)).collect();
    let 总字频: u128 = 去重.values().map(|(_, 频)| *频 as u128).sum();
    let 基线加权: u128 = 去重
        .values()
        .map(|(码, 频)| 口径.上屏码长(码) as u128 * *频 as u128)
        .sum();

    // 3. 按字频降序处理（同频按字码点，保证确定性）。
    //    零频字不参与分配：它们对加权码长没有贡献，不该占掉前缀位、也不该刷出
    //    几万条无意义的简码（CLI 对全量码表补简码时会遇到大量零频冷僻字）。
    let mut 候选: Vec<(char, String, u64)> = 去重
        .into_iter()
        .filter(|(_, (_, 频))| *频 > 0)
        .map(|(字, (码, 频))| (字, 码, 频))
        .collect();
    候选.sort_by(|a, b| b.2.cmp(&a.2).then_with(|| a.0.cmp(&b.0)));

    let mut 条目: Vec<简码条目> = Vec::new();
    // 存「上屏串」而不是码表字符串：不同码串可能补空格后撞成同一个串
    let mut 已占用: HashSet<String> = HashSet::new();
    let mut 各级条数 = [0usize; 3];
    let mut 覆盖字频 = 0u128;
    let mut 简码后加权: u128 = 0;

    for (字, 全码, 字频) in 候选 {
        let 全码长 = 全码.chars().count();
        let 全码上屏长 = 口径.上屏码长(&全码);
        let mut 分配: Option<(String, usize, usize)> = None;

        for 级别 in 1..=3usize {
            if 全码长 <= 级别 {
                continue; // 前缀不比全码短
            }
            let 前缀: String = 全码.chars().take(级别).collect();
            let 码 = if 级别 == 1 {
                match 口径 {
                    // 默认档：一级简码显式带空格，与历史 `简码表.txt` 格式一致（2 键）
                    码长口径::码串长度 => format!("{前缀}_"),
                    // 补空格档：写成单字母，空格交给测评补；写成 `a_` 会被补成 `a__`
                    码长口径::补空格 => 前缀,
                }
            } else {
                前缀
            };
            let 上屏串 = 口径.上屏串(&码);
            let 上屏长 = 口径.上屏码长(&码);
            if 上屏长 >= 全码上屏长 {
                continue; // 该级在该口径下不省键（补空格档的三级简码正是如此）
            }
            if 全码集合.contains(&上屏串) || 已占用.contains(&上屏串) {
                continue;
            }
            已占用.insert(上屏串);
            分配 = Some((码, 级别, 上屏长));
            break;
        }

        let 上屏码长 = match &分配 {
            Some((码, 级别, 上屏长)) => {
                各级条数[级别 - 1] += 1;
                覆盖字频 += 字频 as u128;
                条目.push(简码条目 {
                    字,
                    码: 码.clone(),
                    字频,
                    级别: *级别,
                });
                *上屏长
            }
            None => 全码上屏长,
        };
        简码后加权 += 上屏码长 as u128 * 字频 as u128;
    }

    let 分母 = 总字频 as f64;
    let 统计 = 简码统计 {
        口径,
        全码字数,
        简码字数: 条目.len(),
        各级条数,
        总字频,
        覆盖字频,
        基线码长: if 分母 > 0.0 {
            基线加权 as f64 / 分母
        } else {
            0.0
        },
        简码后码长: if 分母 > 0.0 {
            简码后加权 as f64 / 分母
        } else {
            0.0
        },
    };
    简码结果 { 条目, 统计 }
}

/// `简码表.txt` 全文（仿历史三级分段格式，带效率指标头部）
pub fn 写简码表文本(结果: &简码结果, 字频来源: &str) -> String {
    let s = &结果.统计;
    let mut out = String::new();
    out.push_str("# 简码分配结果（全码算完后自动生成：三级前缀简码，效率优先）\n");
    out.push_str(&format!("# 字频口径: {字频来源}\n"));
    out.push_str("# 分配策略: 按字频降序，每字取「最短且未被占用」的全码前缀；同一简码至多 1 字\n");
    out.push_str(&format!(
        "# 全码字数: {} / 简码字数: {}\n",
        s.全码字数, s.简码字数
    ));
    out.push_str(&format!(
        "# 各级条数: 1级 {} / 2级 {} / 3级 {}\n",
        s.各级条数[0], s.各级条数[1], s.各级条数[2]
    ));
    out.push_str(&format!("# 简码覆盖频率: {:.4}%\n", s.覆盖频率() * 100.0));
    out.push_str(&format!("# 效率口径: {}\n", s.口径.名称()));
    out.push_str(&format!(
        "# 字频加权码长: 全码基线 {:.4} → 简码后 {:.4}（每字省 {:.4} 键）\n",
        s.基线码长,
        s.简码后码长,
        s.省键()
    ));
    match s.口径 {
        码长口径::码串长度 => {
            out.push_str(
                "# 码长计数: 1级 `a_` 2 键 / 2级 `ab` 2 键 / 3级 `abc` 3 键 / 全码 4 键（个别 3 键）\n",
            );
            out.push_str(
                "# 测评对照: 「簡碼效率加權碼長」用纯编码长度，与本档同源（但测评一级简码\n",
            );
            out.push_str("#           常写单字母 `a` 记 1 键，本项目历史格式 `a_` 记 2 键）；\n");
            out.push_str("#           「速度当量/按键数」那条链路会给短码补 `_`，与本档不同。\n");
            out.push_str(
                "# 本项目口径: 每级简码上屏都要按一次空格，测评用码表统一采用补空格档。\n",
            );
        }
        码长口径::补空格 => {
            out.push_str("# 码长计数: 按实际按键数——首选且未满 4 码补一个 `_` 后再计数。\n");
            out.push_str(
                "#            1级 `a`→`a_` 2 键 / 2级 `ab`→`ab_` 3 键 / 3级 `abc`→`abc_` 4 键 / 全码 4 键\n",
            );
            out.push_str(
                "#            三级简码 + 空格 = 4 键、与全码持平，故不分配；一级写成单字母，空格只补一次。\n",
            );
            out.push_str("#            未计入全码重码的选重键（测评按键表里那部分会再 +1 键）。\n");
            out.push_str("# 本项目口径: 本档即测评用码表（每级简码都带空格上屏）。\n");
            out.push_str(
                "# 测评对照: 本档对应「速度当量/按键数」链路；「簡碼效率加權碼長」用纯编码\n",
            );
            out.push_str("#           长度，不含下划线与选重键，与本档不是同一指标。\n");
        }
    }
    out.push_str("# 开关: [shortcode] padding_space / CLI --padding-space（缺省 true=补空格档）\n");
    out.push_str("# 提示: 两档的码长数值不可直接比较，只有同档内比较才有意义。\n");
    out.push_str("#\n");

    for 级别 in 1..=3usize {
        let mut 本级: Vec<&简码条目> = 结果.条目.iter().filter(|e| e.级别 == 级别).collect();
        本级.sort_by(|a, b| a.码.cmp(&b.码).then_with(|| a.字.cmp(&b.字)));
        let 规则 = match (级别, s.口径) {
            (1, 码长口径::码串长度) => "全码首键 + 空格",
            (1, 码长口径::补空格) => "全码首键（空格上屏）",
            (2, _) => "全码前 2 键",
            _ => "全码前 3 键",
        };
        out.push_str(&format!("# === {级别}级简码（{规则}）===\n"));
        out.push_str("# 汉字\t简码\t字频\n");
        for e in &本级 {
            out.push_str(&format!("{}\t{}\t{}\n", e.字, e.码, e.字频));
        }
        out.push_str(&format!("# 该级简码覆盖 {} 字\n", 本级.len()));
        out.push_str("#\n");
    }
    out
}

/// 追加进 `合并码表.txt` 的简码段：每字一行 `字<TAB>简码`，不带字频列。
pub fn 写合并简码段(结果: &简码结果) -> String {
    let mut 本级: Vec<&简码条目> = 结果.条目.iter().collect();
    本级.sort_by(|a, b| {
        a.级别
            .cmp(&b.级别)
            .then_with(|| a.码.cmp(&b.码))
            .then_with(|| a.字.cmp(&b.字))
    });
    let mut out = String::with_capacity(本级.len() * 8 + 64);
    // 注释行测评解析器会跳过；标明口径，避免同一份合并码表被两种口径的产物弄混
    out.push_str(&format!("# 简码口径: {}\n", 结果.统计.口径.名称()));
    for e in 本级 {
        out.push_str(&format!("{}\t{}\n", e.字, e.码));
    }
    out
}

/// `合并码表.txt` 里简码段的起始标记；重复运行时靠它替换旧段，保证幂等。
/// 码表解析器会跳过 `#` 开头的行，不会影响测评。
const 简码段标记: &str = "# === 三级前缀简码（shortcode 自动生成；重跑会替换本段）===";

/// 写出 `简码表.txt`，并把简码段并进已有的 `合并码表.txt`。
///
/// `完整码表.txt` 故意保持纯全码：字根图 / Rime 转换 / 句子解码都按「一行一字全码」
/// 读它，混入简码会破坏这些下游。要看简码效率请测评 `合并码表.txt`。
///
/// 合并码表是**同一份产物的幂等更新**，所以按标记截掉旧段再写，不走
/// `write_output` 的归档逻辑——否则每重算一次简码就留一份 `合并码表.txt.<时间戳>`。
pub fn 保存(dir: &str, 结果: &简码结果, 字频来源: &str) {
    crate::fsutil::write_output(format!("{dir}/简码表.txt"), 写简码表文本(结果, 字频来源));

    let 路径 = format!("{dir}/合并码表.txt");
    let Ok(原文) = std::fs::read_to_string(&路径) else {
        eprintln!("⚠️ 读不到 {路径}，简码只写入 简码表.txt");
        return;
    };
    let 基础 = match 原文.find(简码段标记) {
        Some(起点) => &原文[..起点],
        None => 原文.as_str(),
    };
    let mut 新文 = String::with_capacity(基础.len() + 结果.条目.len() * 8 + 128);
    新文.push_str(基础);
    if !新文.is_empty() && !新文.ends_with('\n') {
        新文.push('\n');
    }
    新文.push_str(简码段标记);
    新文.push('\n');
    新文.push_str(&写合并简码段(结果));
    if let Err(e) = std::fs::write(&路径, 新文) {
        eprintln!("⚠️ 写回 {路径} 失败: {e}");
    }
}

/// 控制台上一行说清「效率优先」的结果
pub fn 打印统计(s: &简码统计) {
    println!(
        "📄 三级前缀简码 [{}]: {} 字（1级 {} / 2级 {} / 3级 {}），覆盖频率 {:.4}%，\
         字频加权码长 {:.4} → {:.4}（每字省 {:.4} 键）",
        s.口径.名称(),
        s.简码字数,
        s.各级条数[0],
        s.各级条数[1],
        s.各级条数[2],
        s.覆盖频率() * 100.0,
        s.基线码长,
        s.简码后码长,
        s.省键()
    );
}

/// 从任意字频/拆分表读「字 → 字频」：取每行最后一列能解析成整数的记录。
///
/// 同时兼容 `字<TAB>字频`（`全字频表.txt`）与 `字<TAB>根序列<TAB>字频`（拆分表）。
pub fn 读字频(文本: &str) -> HashMap<char, u64> {
    let mut 表: HashMap<char, u64> = HashMap::new();
    for 行 in 文本.lines() {
        let 行 = 行.trim_end_matches('\r');
        if 行.is_empty() || 行.starts_with('#') {
            continue;
        }
        let 列: Vec<&str> = 行.split('\t').collect();
        if 列.len() < 2 {
            continue;
        }
        let Some(字) = 列[0].chars().next() else {
            continue;
        };
        if let Ok(频) = 列[列.len() - 1].trim().parse::<u64>() {
            表.entry(字)
                .and_modify(|旧| *旧 = (*旧).max(频))
                .or_insert(频);
        }
    }
    表
}

/// 把「字频表」套到「全码表」上，得到算法输入。字频表里没有的字按 0 处理
/// （仍可参与分配，但不会抢高频字的码位）。
pub fn 合成全码条目(全码文本: &str, 字频: &HashMap<char, u64>) -> Vec<全码条目> {
    let mut 出 = Vec::new();
    for 行 in 全码文本.lines() {
        let 行 = 行.trim_end_matches('\r');
        if 行.is_empty() || 行.starts_with('#') {
            continue;
        }
        let 列: Vec<&str> = 行.split('\t').collect();
        if 列.len() < 2 {
            continue;
        }
        let Some(字) = 列[0].chars().next() else {
            continue;
        };
        let 码 = 列[1].trim();
        if 码.is_empty() || 列[0].chars().count() != 1 {
            continue;
        }
        出.push((字, 码.to_string(), 字频.get(&字).copied().unwrap_or(0)));
    }
    出
}

