// =========================================================================
// 🌱 星陈专用 prepare 链路（与 魔灵 / 灵明 完全分开）
// =========================================================================
//
// 为什么单独一套：星陈 与另两套方案的输入结构本来就不同，硬凑在一条共用
// 步骤表里，任何一方调参都会波及另一方。
//
// 1. **步骤 6 用星陈自己的口径重建 `字根声韵.txt`**。
//    魔灵/灵明 的声码就是拼音声母，所以才有「非常用字根不取声母」的削减；
//    星陈 的小码不是声母（`声码键位 = Some("weisdfjklmvnhgur")`，由退火在
//    这 16 个键里分配）。这张表在星陈链路只有一个用途：让步骤 9 / 12 判断
//    某个根**有没有小码槽**（声码长度 > 1 才有）。若沿用魔灵的削减，`亻 氵 扌
//    艹 讠` 这类部件根会被判成无声母、永远拿不到 `.1` 槽，键位表里只剩大码。
//    因此星陈口径是「查得到读音就有小码」，见 [`步骤6_星陈声韵表`]。
//
// 2. **约束直接写槽位号 `.0` / `.1`**。
//    魔灵/灵明 是先写 `.A` / `.S` / `.Y`，再靠步骤 13 按「简码是否开启」改名；
//    星陈 只取大码与小码、没有韵码，槽位本就是 0 和 1，直接写省掉一次改名。
//    因此步骤 13 在星陈链路里是空操作（简码功能整体移除后，该步骤在**任何**
//    链路里都已置空，仅保留编号占位）。
//
// 3. 与魔灵/灵明 共用的只有 0~5 步（全字频、字符集、算码字频、拆分表、
//    字根频率、字根读音）——这几步不吃方案的编码规则，重复实现只会得到两份
//    必须同步维护的代码，故仍走 [`crate::prepare::共用步骤`]。
// =========================================================================

use crate::prepare::{inputs, roots, 上下文, 共用步骤};

/// 星陈的单步入口：按步骤号分派，与魔灵/灵明的步骤表互不相干
pub fn 步骤(上: &上下文, 步骤: usize) -> Result<(), String> {
    match 步骤 {
        0..=5 => 共用步骤(上, 步骤)?,
        6 => 步骤6_星陈声韵表(上)?,
        // 7 / 10 / 11 是已移除的步骤（飞键候选、飞键约束、动态字根）
        7 | 10 | 11 => {}
        8 => inputs::大码约束(上, ".0")?,
        9 => inputs::声韵约束(上, ".1", ".2")?,
        12 => inputs::编码展开(上, true)?,
        13 => 步骤13_已就位()?,
        other => return Err(format!("步骤号 {other} 超出 0~13")),
    }
    Ok(())
}

/// 步骤 6：星陈自己的 `字根声韵.txt`
///
/// 与魔灵/灵明 的关键差异：**不做「非常用字根不取声母」的削减**。
///
/// 这张表在星陈里不提供码位（小码由退火在 `声码键位` 内分配），只有一个用途——
/// 步骤 9 / 12 用「声码长度 > 1」判断该字根**有没有小码槽**（见
/// `inputs::展开` 里的 `有声母`）。一旦沿用魔灵的削减，`亻 氵 扌 艹 讠` 这类
/// 不成字部件根就被判成「无声母」，永远拿不到 `.1` 槽，`字根键位表` 里只剩
/// 一个大码。
///
/// 星陈的口径是：**只要查得到读音就有小码**（只有 修正表 里显式写成单字符的
/// `彳 亍 咼 尢`、以及完全查不到读音的花括号无名部件 / 符号根仍是单字符）。
/// 该表由 字根读音 + 字根频率 确定性推导，因此无条件重建，避免残留旧口径。
fn 步骤6_星陈声韵表(上: &上下文) -> Result<(), String> {
    println!(
        "(6) 生成星陈字根声韵表 {}（不做非常用字根削声母）...",
        上.字根表
    );
    let 出 = roots::生成字根声韵表(上, false, true)?;
    let 名 = 上.字根表.clone();
    上.写(&名, &出)
}

/// 步骤 13：星陈 的约束已经是 `.0` / `.1`，不需要改名
fn 步骤13_已就位() -> Result<(), String> {
    println!("(13) 星陈 的约束已直接写成 .0/.1 槽位，跳过改名");
    Ok(())
}
